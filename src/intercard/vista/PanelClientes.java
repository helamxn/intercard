    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        Cliente cliente;
        try {
            cliente = sistema.buscarCliente(txtBuscarDni.getText().trim());
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
            return;
        }
        if (cliente == null) {
            JOptionPane.showMessageDialog(this, "No se encontró un cliente con ese DNI.",
                    "Búsqueda", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tablaClientes.getModel();
        modelo.setRowCount(0);
        agregarFila(cliente);
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnMostrarTodosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarTodosActionPerformed
        txtBuscarDni.setText("");
        actualizarTabla();
    }//GEN-LAST:event_btnMostrarTodosActionPerformed

    /**
     * Vuelve a llenar la tabla con todos los clientes del sistema.
     */
    public void actualizarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tablaClientes.getModel();
        modelo.setRowCount(0);
        try {
            for (Cliente cliente : sistema.getClientes()) {
                agregarFila(cliente);
            }
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
        }
    }

    private void agregarFila(Cliente cliente) {
        DefaultTableModel modelo = (DefaultTableModel) tablaClientes.getModel();
        modelo.addRow(new Object[]{
            cliente.getDni(),
            cliente.getNombres(),
            cliente.getApellidos(),
            cliente.getTelefono(),
            cliente.getCorreo()
        });
    }

    private void limpiarFormulario() {
        txtDni.setText("");
        txtNombres.setText("");
        txtApellidos.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        txtDni.requestFocus();
    }

