    private void btnConsultarDniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarDniActionPerformed
        String dni = txtDni.getText().trim();
        if (!ConsultaDni.esDniValido(dni)) {
            JOptionPane.showMessageDialog(this, "El DNI debe tener 8 dígitos.",
                    "DNI inválido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Mientras se espera la respuesta, se desactiva el botón
        btnConsultarDni.setEnabled(false);
        btnConsultarDni.setText("Consultando...");

        // La consulta a internet se hace en segundo plano con un SwingWorker,
        // así la ventana no se congela mientras llega la respuesta.
        SwingWorker<Persona, Void> tarea = new SwingWorker<>() {

            @Override
            protected Persona doInBackground() throws Exception {
                // Se ejecuta en segundo plano
                return consultaDni.consultar(dni);
            }

            @Override
            protected void done() {
                // Se ejecuta al terminar la consulta; aquí sí se puede modificar la ventana
                btnConsultarDni.setEnabled(true);
                btnConsultarDni.setText("Consultar DNI");
                try {
                    Persona persona = get();
                    if (persona == null) {
                        JOptionPane.showMessageDialog(PanelClientes.this,
                                "No se encontraron datos para el DNI " + dni + ".\n"
                                + "Puede escribir los nombres y apellidos manualmente.",
                                "DNI no encontrado", JOptionPane.INFORMATION_MESSAGE);
                    } else {
                        txtNombres.setText(persona.getNombres());
                        txtApellidos.setText(persona.getApellidos());
                        txtTelefono.requestFocus();
                    }
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(PanelClientes.this,
                            "No se pudo consultar el DNI (revise su conexión a internet).\n"
                            + "Puede escribir los nombres y apellidos manualmente.",
                            "Error de conexión", JOptionPane.ERROR_MESSAGE);
                }
            }
        };
        tarea.execute();
    }//GEN-LAST:event_btnConsultarDniActionPerformed

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String dni = txtDni.getText().trim();
        String nombres = txtNombres.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();

        if (dni.isEmpty() || nombres.isEmpty() || apellidos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El DNI, los nombres y los apellidos son obligatorios.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!ConsultaDni.esDniValido(dni)) {
            JOptionPane.showMessageDialog(this, "El DNI debe tener 8 dígitos.",
                    "DNI inválido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Cliente cliente = new Cliente(dni, nombres, apellidos, telefono, correo);
        try {
            if (sistema.registrarCliente(cliente)) {
                JOptionPane.showMessageDialog(this, "Cliente registrado correctamente.");
                limpiarFormulario();
                actualizarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "Ya existe un cliente con el DNI " + dni + ".",
                        "Cliente duplicado", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

