    /**
     * Crea un objeto de cada sección y lo agrega al panel central.
     */
    private void agregarSecciones() {
        panelInicio = new PanelInicio(sistema);
        panelClientes = new PanelClientes(sistema);
        panelVentaTarjeta = new PanelVentaTarjeta(sistema, empleado);
        panelRecarga = new PanelRecarga(sistema, empleado);
        panelTarjetas = new PanelTarjetas(sistema);
        panelHistorialVentas = new PanelHistorialVentas(sistema);

        panelContenido.add(panelInicio, INICIO);
        panelContenido.add(panelClientes, CLIENTES);
        panelContenido.add(panelVentaTarjeta, VENDER_TARJETA);
        panelContenido.add(panelRecarga, RECARGAR_TARJETA);
        panelContenido.add(panelTarjetas, TARJETAS);
        panelContenido.add(panelHistorialVentas, HISTORIAL);
    }

    /**
     * Muestra en el panel central la sección indicada.
     */
    private void mostrarSeccion(String nombreSeccion, String titulo) {
        CardLayout cardLayout = (CardLayout) panelContenido.getLayout();
        cardLayout.show(panelContenido, nombreSeccion);
        lblEstado.setText("Sección actual: " + titulo);
    }

