    private void btnBuscarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarClienteActionPerformed
        String dni = txtDniCliente.getText().trim();
        try {
            clienteSeleccionado = sistema.buscarCliente(dni);
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
            return;
        }
        if (clienteSeleccionado == null) {
            lblNombreCliente.setText("-");
            JOptionPane.showMessageDialog(this,
                    "No se encontró el cliente. Regístrelo primero en la sección Clientes.",
                    "Cliente no encontrado", JOptionPane.WARNING_MESSAGE);
        } else {
            lblNombreCliente.setText(clienteSeleccionado.getNombreCompleto());
        }
    }//GEN-LAST:event_btnBuscarClienteActionPerformed

    private void btnCalcularTotalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularTotalActionPerformed
        double saldoInicial = leerSaldoInicial();
        if (saldoInicial >= 0) {
            double total = SistemaVentas.COSTO_TARJETA + saldoInicial;
            lblTotalPagar.setText(String.format("%.2f", total));
        }
    }//GEN-LAST:event_btnCalcularTotalActionPerformed

    private void btnRegistrarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVentaActionPerformed
        if (clienteSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Primero busque y seleccione un cliente.",
                    "Falta el cliente", JOptionPane.WARNING_MESSAGE);
            return;
        }
        double saldoInicial = leerSaldoInicial();
        if (saldoInicial < 0) {
            return;
        }

        try {
            Venta venta = sistema.venderTarjeta(clienteSeleccionado, saldoInicial, empleado);
            JOptionPane.showMessageDialog(this,
                    "Venta N° " + venta.getNumero() + " registrada.\n"
                    + "Tarjeta: " + venta.getTarjeta().getCodigo() + "\n"
                    + "Total cobrado: S/ " + String.format("%.2f", venta.getMonto()));
            limpiarFormulario();
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
        }
    }//GEN-LAST:event_btnRegistrarVentaActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        limpiarFormulario();
    }//GEN-LAST:event_btnLimpiarActionPerformed

    /**
     * Deja el formulario listo para una nueva venta.
     */
    public void limpiarFormulario() {
        clienteSeleccionado = null;
        txtDniCliente.setText("");
        lblNombreCliente.setText("-");
        try {
            txtCodigo.setText(sistema.obtenerSiguienteCodigoTarjeta());
        } catch (SQLException e) {
            txtCodigo.setText("-");
            Mensajes.errorBaseDatos(this, e);
        }
        txtCosto.setText(String.format("%.2f", SistemaVentas.COSTO_TARJETA));
        txtSaldoInicial.setText(String.format("%.2f", 0.0));
        lblTotalPagar.setText(String.format("%.2f", SistemaVentas.COSTO_TARJETA));
    }

    /**
     * Lee el saldo inicial escrito por el usuario.
     * Devuelve -1 si el valor no es válido.
     */
    private double leerSaldoInicial() {
        try {
            double saldo = Double.parseDouble(txtSaldoInicial.getText().trim().replace(",", "."));
            if (saldo < 0) {
                JOptionPane.showMessageDialog(this, "El saldo inicial no puede ser negativo.",
                        "Dato inválido", JOptionPane.WARNING_MESSAGE);
                return -1;
            }
            return saldo;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un saldo inicial válido. Ejemplo: 10.50",
                    "Dato inválido", JOptionPane.WARNING_MESSAGE);
            return -1;
        }
    }

