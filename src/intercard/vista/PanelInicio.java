    /**
     * Crea los gráficos una sola vez y los coloca en sus paneles contenedores.
     */
    private void crearGraficos() {
        // Gráfico de barras: cuánto dinero ingresó por cada tipo de operación
        datosIngresos = new DefaultCategoryDataset();
        JFreeChart graficoIngresos = ChartFactory.createBarChart(
                null,                   // sin título (ya lo indica el borde del panel)
                "Tipo de operación",    // texto del eje horizontal
                "Monto (S/)",           // texto del eje vertical
                datosIngresos);
        panelGraficoIngresos.add(new ChartPanel(graficoIngresos), BorderLayout.CENTER);

        // Gráfico circular: cuántas tarjetas están activas y cuántas bloqueadas
        datosTarjetas = new DefaultPieDataset<>();
        JFreeChart graficoTarjetas = ChartFactory.createPieChart(null, datosTarjetas);
        panelGraficoTarjetas.add(new ChartPanel(graficoTarjetas), BorderLayout.CENTER);
    }

    /**
     * Vuelve a leer los datos del sistema y actualiza los totales y los gráficos.
     */
    public void actualizarDatos() {
        try {
            // Totales
            lblTotalClientes.setText(String.valueOf(sistema.contarClientes()));
            lblTotalTarjetas.setText(String.valueOf(sistema.contarTarjetas()));
            lblTotalVentas.setText(String.valueOf(sistema.contarVentas()));
            lblMontoTotal.setText("S/ " + String.format("%.2f", sistema.calcularMontoTotalVendido()));

            // Gráfico de barras: (valor, serie, categoría)
            datosIngresos.setValue(sistema.calcularMontoPorConcepto(Venta.VENTA_TARJETA), "Monto", Venta.VENTA_TARJETA);
            datosIngresos.setValue(sistema.calcularMontoPorConcepto(Venta.RECARGA), "Monto", Venta.RECARGA);

            // Gráfico circular: se borra y se vuelve a llenar para mostrar la cantidad en cada nombre
            int activas = sistema.contarTarjetasActivas();
            int bloqueadas = sistema.contarTarjetasBloqueadas();
            datosTarjetas.clear();
            datosTarjetas.setValue("Activas (" + activas + ")", activas);
            datosTarjetas.setValue("Bloqueadas (" + bloqueadas + ")", bloqueadas);
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
        }
    }

