    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String usuario = txtUsuario.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());

        if (usuario.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese su usuario y contraseña.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Empleado empleado;
        try {
            empleado = sistema.iniciarSesion(usuario, contrasena);
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
            return;
        }
        if (empleado == null) {
            JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos.",
                    "Acceso denegado", JOptionPane.ERROR_MESSAGE);
            txtContrasena.setText("");
            return;
        }

        // Abre la ventana principal y cierra el login
        VentanaPrincipal principal = new VentanaPrincipal(sistema, empleado);
        principal.setVisible(true);
        dispose();
    }//GEN-LAST:event_btnIngresarActionPerformed

