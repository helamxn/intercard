    /**
     * Prepara el selector de fecha (JSpinner): empieza en el día de hoy, se muestra
     * como día/mes/año y se cambia con las flechas o escribiendo la fecha.
     * El modelo de fechas se configura aquí, en el código, porque el diseñador
     * crea el JSpinner con un modelo de números por defecto.
     */
    private void configurarSelectorFecha() {
        spnFecha.setModel(new SpinnerDateModel());
        spnFecha.setEditor(new JSpinner.DateEditor(spnFecha, "dd/MM/yyyy"));
        spnFecha.setEnabled(false);
    }

    /**
     * Devuelve el día elegido en el selector de fecha.
     * (JSpinner trabaja con java.util.Date; aquí se convierte a LocalDate)
     */
    private LocalDate obtenerFechaSeleccionada() {
        Date fecha = (Date) spnFecha.getValue();
        return fecha.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    }

    /**
     * Llena la tabla con las operaciones que cumplen los filtros elegidos
     * y muestra cuántas son y la suma de sus montos.
     */
    public void actualizarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tablaVentas.getModel();
        modelo.setRowCount(0);

        // Filtro por tipo (null = todos los tipos)
        String concepto = null;
        String tipoSeleccionado = (String) cboTipo.getSelectedItem();
        if (!tipoSeleccionado.equals("Todas")) {
            concepto = tipoSeleccionado;
        }

        // Filtro por fecha (null = todas las fechas)
        LocalDate fecha = null;
        if (chkPorFecha.isSelected()) {
            fecha = obtenerFechaSeleccionada();
        }

        ArrayList<Venta> ventas;
        try {
            ventas = sistema.buscarVentas(concepto, fecha);
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
            return;
        }

        double total = 0;
        for (Venta venta : ventas) {
            modelo.addRow(new Object[]{
                venta.getNumero(),
                venta.getFecha().format(FORMATO_FECHA_HORA),
                venta.getConcepto(),
                venta.getCliente().getNombreCompleto(),
                venta.getTarjeta().getCodigo(),
                venta.getEmpleado().getNombreCompleto(),
                String.format("%.2f", venta.getMonto())
            });
            total = total + venta.getMonto();
        }

        if (ventas.size() == 1) {
            lblCantidad.setText("1 operación");
        } else {
            lblCantidad.setText(ventas.size() + " operaciones");
        }
        lblTotal.setText("S/ " + String.format("%.2f", total));
    }

