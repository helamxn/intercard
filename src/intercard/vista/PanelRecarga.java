    private void btnBuscarTarjetaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarTarjetaActionPerformed
        try {
            tarjetaSeleccionada = sistema.buscarTarjeta(txtCodigoTarjeta.getText().trim());
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
            return;
        }
        if (tarjetaSeleccionada == null) {
            limpiarDatosTarjeta();
            JOptionPane.showMessageDialog(this, "No se encontró una tarjeta con ese código.",
                    "Tarjeta no encontrada", JOptionPane.WARNING_MESSAGE);
        } else {
            mostrarDatosTarjeta();
        }
    }//GEN-LAST:event_btnBuscarTarjetaActionPerformed

    private void btnRecargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRecargarActionPerformed
        if (tarjetaSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Primero busque una tarjeta.",
                    "Falta la tarjeta", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!tarjetaSeleccionada.isActiva()) {
            JOptionPane.showMessageDialog(this, "La tarjeta está bloqueada y no se puede recargar.",
                    "Tarjeta bloqueada", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double monto = Double.parseDouble((String) cboMonto.getSelectedItem());
        try {
            sistema.recargarTarjeta(tarjetaSeleccionada, monto, empleado);
            mostrarDatosTarjeta();
            JOptionPane.showMessageDialog(this,
                    "Recarga de S/ " + String.format("%.2f", monto) + " realizada correctamente.");
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
        }
    }//GEN-LAST:event_btnRecargarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        limpiarFormulario();
    }//GEN-LAST:event_btnLimpiarActionPerformed

    /**
     * Deja el formulario listo para una nueva recarga.
     */
    public void limpiarFormulario() {
        txtCodigoTarjeta.setText("");
        cboMonto.setSelectedIndex(0);
        limpiarDatosTarjeta();
    }

    private void limpiarDatosTarjeta() {
        tarjetaSeleccionada = null;
        lblTitular.setText("-");
        lblSaldoActual.setText("-");
        lblEstadoTarjeta.setText("-");
    }

    private void mostrarDatosTarjeta() {
        lblTitular.setText(tarjetaSeleccionada.getTitular().getNombreCompleto());
        lblSaldoActual.setText(String.format("%.2f", tarjetaSeleccionada.getSaldo()));
        lblEstadoTarjeta.setText(tarjetaSeleccionada.getEstadoTexto());
    }

